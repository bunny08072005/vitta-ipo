export function getAllIPOs() { return ipoData; }
export function getIPOBySlug(slug) { return ipoData.find(ipo => ipo.id === slug); }
export function getIPOsByStatus(status) { return ipoData.filter(ipo => ipo.status === status); }
export function getStatusLabel(status) {
  const labels = { upcoming: 'Upcoming', open: 'Open Now', closed: 'Listing Soon', listed: 'Listed', sme: 'SME' };
  return labels[status] || status;
}
export function getStatusBadgeClass(status) {
  const classes = { upcoming: 'badge-amber', open: 'badge-green', closed: 'badge-cyan', listed: 'badge-purple', sme: 'badge-purple' };
  return classes[status] || 'badge-green';
}
export function formatCurrency(num) {
  if (num >= 10000) return `₹${(num/10000).toFixed(1)}T Cr`;
  if (num >= 100) return `₹${num.toLocaleString('en-IN')} Cr`;
  return `₹${num} Cr`;
}
export function formatDate(dateStr) {
  if (!dateStr) return 'Date TBD';
  const d = new Date(dateStr);
  if (isNaN(d.getTime())) return 'Date TBD';
  return d.toLocaleDateString('en-IN', { day: 'numeric', month: 'short', year: 'numeric' });
}
